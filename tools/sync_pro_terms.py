# -*- coding: utf-8 -*-
"""Generate the Kapture Pro section of /terms/ from the backend's single source.

    python3 tools/sync_pro_terms.py [path/to/pro_terms.json]

The wording lives in kapture-supabase/supabase/functions/_shared/pro_terms.json,
which also feeds Stripe Checkout and the purchase-confirmation email, so the
site, the checkout and the email a customer keeps always say the same thing.
This writes:
  terms/index.html     the English section, between the pro-terms markers
  tools/t_pro_terms.py the translations for build_i18n.py: de, fr, es and it are
                       translated; ja, ko, zh and pt-br keep the English section
                       (marked lang="en") under a translated notice.
Then run tools/build_i18n.py as usual.
"""
import html, json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
DEFAULT = ROOT.parent / 'kapture-supabase' / 'supabase' / 'functions' / '_shared' / 'pro_terms.json'
TRANSLATED = ['de', 'fr', 'es', 'it']
ENGLISH_ONLY = ['ja', 'ko', 'zh', 'pt-br']
START, END = '<!-- pro-terms:start -->', '<!-- pro-terms:end -->'
NOTICE = 'These Kapture Pro terms are part of these terms in every language version of this page.'
NOTICE_TRANSLATED = {
    'de': 'Diese Bedingungen für Kapture Pro sind Teil dieser Bedingungen.',
    'fr': 'Ces conditions de Kapture Pro font partie des présentes conditions.',
    'es': 'Estas condiciones de Kapture Pro forman parte de estos términos.',
    'it': 'Queste condizioni di Kapture Pro fanno parte di questi termini.',
}


def inline(text):
    """Escape, then turn [text](url) into a link, as the email does."""
    out, last = [], 0
    for m in re.finditer(r'\[([^\]]+)\]\(([^)]+)\)', text):
        out.append(html.escape(text[last:m.start()], quote=False))
        out.append('<a href="%s">%s</a>' % (html.escape(m.group(2)), html.escape(m.group(1), quote=False)))
        last = m.end()
    out.append(html.escape(text[last:], quote=False))
    return ''.join(out)


def blocks(locale_copy):
    for b in locale_copy['terms']:
        yield ('h3', inline(b['h'])) if 'h' in b else ('p', inline(b['p']))


def main():
    src = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else DEFAULT)
    data = json.loads(src.read_text(encoding='utf-8'))
    loc = data['locales']
    en = list(blocks(loc['en']))
    for l in TRANSLATED:
        if [t for t, _ in blocks(loc[l])] != [t for t, _ in en]:
            sys.exit('%s: the section does not have the same structure as English' % l)

    section = '\n'.join(
        ['      %s' % START,
         '      <h2 id="pro">Kapture Pro</h2>',
         '      <p>%s</p>' % NOTICE,
         '      <div lang="en">']
        + ['      <%s>%s</%s>' % (t, s, t) for t, s in en]
        + ['      </div>',
           '      <!-- Generated by tools/sync_pro_terms.py from %s (%s). Do not edit by hand. -->' % (src.name, data['version']),
           '      %s' % END])

    page = ROOT / 'terms' / 'index.html'
    s = page.read_text(encoding='utf-8')
    if START in s:
        s = re.sub(re.escape(START) + r'.*?' + re.escape(END), section.strip(), s, count=1, flags=re.S)
    else:
        # First run: replace the hand-written section, from its heading to the next one.
        m = re.search(r'      <h2 id="pro">Kapture Pro</h2>.*?(?=\n      <h2>)', s, flags=re.S)
        if not m:
            sys.exit('could not find the Kapture Pro section in terms/index.html')
        s = s[:m.start()] + section + '\n' + s[m.end():]
    page.write_text(s, encoding='utf-8')

    # Translations, keyed by the English text exactly as it appears in the page.
    table = {}
    for i, (t, s_en) in enumerate(en):
        entry = {l: s_en for l in ENGLISH_ONLY}
        for l in TRANSLATED:
            entry[l] = list(blocks(loc[l]))[i][1]
        table['<%s>%s</%s>' % (t, s_en, t)] = {l: '<%s>%s</%s>' % (t, v, t) for l, v in entry.items()}
    # The section wrapper: translated languages say so, the others stay marked English.
    table['<div lang="en">'] = {**{l: '<div lang="en">' for l in ENGLISH_ONLY}, **{l: '<div lang="%s">' % l for l in TRANSLATED}}

    out = ['# -*- coding: utf-8 -*-',
           '"""GENERATED by tools/sync_pro_terms.py from pro_terms.json (%s). Do not edit."""' % data['version'],
           '', 'NOTICE_TRANSLATED = %r' % NOTICE_TRANSLATED, '', 'PRO = {']
    for k, v in table.items():
        out.append('%r: %r,' % (k, v))
    out.append('}')
    (ROOT / 'tools' / 't_pro_terms.py').write_text('\n'.join(out) + '\n', encoding='utf-8')
    print('terms/index.html and tools/t_pro_terms.py written from %s (%s), %d blocks'
          % (src.name, data['version'], len(en)))


if __name__ == '__main__':
    main()
